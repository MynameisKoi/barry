"""Robot Simulator for BARRY.

A fake DOGZILLA that implements the full v1 ``RobotInterface`` but only
updates numbers in memory (position, heading, battery, tracked style/posture).
Use it to develop and test the backend, the Pi Robot API and the Quest app
without the physical robot.

Selected with ``ROBOT_MODE=simulator`` (the legacy ``simulation`` is accepted
by ``RobotConfig.from_env``).

What is simulated vs. what is real
----------------------------------
Everything here is a *model*, not a measurement of real hardware:

* Distances and angles per tick (``step_m``, ``turn_deg``) are arbitrary
  simulation constants, **UNCALIBRATED** against the DOGZILLA S2.
* The v1 safety rules ARE the real ones: the dead zone, intensity scaling,
  ``max_motion_scale``, the attitude limits, the unsafe-combination table, the
  action allowlist and the e-stop latch all come from ``backend.robot.config``
  and ``backend.robot.interface`` so the simulator rejects exactly what the
  hardware implementation must reject.
* "Measured" telemetry (battery, orientation) is generated by the simulator
  and reported as if it were a sensor read, so clients exercise the same code
  path they will use with hardware. It is never real data.

Motion model
------------
Heading is in degrees: 0 = East (+x), 90 = North (+y); positive = counter-
clockwise (turning left).

* ``move_analog``: each call is one tick. ``forward`` moves along the heading,
  ``strafe`` (+ = left) moves perpendicular to it, ``turn`` (+ = left) changes
  the heading. Each axis is dead-zoned, then multiplied by the intensity
  scale and ``config.max_motion_scale``.
* ``move_discrete``: one tick using the SDK step from
  ``DISCRETE_STEP_FOR_INTENSITY``, converted to meters/degrees by dividing by
  the SDK axis limit.
* legacy ``move``: unchanged behaviour (``left``/``right`` turn in place by
  ``turn_deg``) so ``backend/main.py`` and ``tests/test_robot.py`` keep working.

A movement command leaves the simulated robot in the ``moving`` state until
``stop()`` (mirrors the SDK, where ``move_x`` etc. keep walking until told to
stop). The Pi-side watchdog, not the simulator, is what issues that stop when
commands go quiet.

This module must stay self-contained: it imports nothing from the laptop-only
parts of the backend (database, missions, models), so it can run on the Pi.
"""

from __future__ import annotations

from dataclasses import dataclass, replace
from datetime import datetime, timezone
import math
import threading
from typing import Any, Dict, List, Optional

from backend.robot.config import (
    APPROVED_ACTIONS,
    DISCRETE_STEP_FOR_INTENSITY,
    MOTION_SCALE_FOR_INTENSITY,
    SDK_VX_MAX,
    SDK_VY_MAX,
    SDK_VYAW_MAX,
    SDK_VYAW_MIN_NONZERO,
    RobotConfig,
    check_attitude,
    check_combination,
)
from backend.robot.legacy import legacy_status_blocks
from backend.robot.interface import (
    ActionInfo,
    CommandResult,
    CommandStatus,
    ControlState,
    Direction,
    HeightPreset,
    Intensity,
    MotionCommand,
    MovementStyle,
    Orientation,
    Posture,
    RobotInterface,
    RobotMode,
    Telemetry,
    apply_dead_zone,
)

# Battery cost per tick, in percent.
_DRAIN_PER_STEP = 0.1
_DRAIN_PER_TURN = 0.08

_MOVE_ACTIONS = {"forward", "backward", "left", "right"}

#: Firmware string reported by the simulated ``read_version()``.
_SIM_FIRMWARE = "simulator-1.0"


@dataclass
class _LegacyStopResult(CommandResult):
    """``CommandResult`` that also answers the legacy ``result["success"]`` lookups.

    ``stop()`` changed return type from the legacy dict to ``CommandResult`` in
    v1, but ``tests/test_robot.py`` and ``backend/main.py`` still index the
    result like a dict. This shim keeps both working until they migrate.
    """

    _legacy: Optional[Dict[str, Any]] = None

    def __getitem__(self, key: str) -> Any:
        if self._legacy is None or key not in self._legacy:
            raise KeyError(key)
        return self._legacy[key]

    def get(self, key: str, default: Any = None) -> Any:
        return (self._legacy or {}).get(key, default)


class RobotSimulator(RobotInterface):
    """Simulates DOGZILLA quadruped movement and telemetry."""

    def __init__(
        self,
        config: Optional[RobotConfig] = None,
        battery_level: float = 98.5,
        step_m: float = 1.0,
        turn_deg: float = 15.0,
    ) -> None:
        """
        :param config: Deployment settings (dead zone, motion scale). Defaults
                       to ``RobotConfig()`` so the simulator never reads the
                       environment implicitly.
        :param battery_level: Starting battery percentage (0-100).
        :param step_m: Meters travelled per tick at full SDK forward value.
        :param turn_deg: Degrees turned per tick at full SDK turn value.
        """
        self.config: RobotConfig = config if config is not None else RobotConfig()
        self._connected: bool = True
        self.mode: str = "simulation"  # legacy status string, see get_status()
        self.battery_level: float = max(0.0, min(100.0, battery_level))
        self.step_m = step_m
        self.turn_deg = turn_deg

        self.x: float = 0.0
        self.y: float = 0.0
        self.heading: float = 0.0
        self.speed: float = 0.0
        self.last_command: str = "stop"
        self.emergency_stopped: bool = False

        # Tracked (commanded) state; see ControlState.
        self.intensity: Intensity = Intensity.MEDIUM
        self.gait = MovementStyle().gait
        self.posture: Posture = Posture()
        self.moving: bool = False
        self._imu_enabled: bool = False

        #: SDK-level values of the last dispatched motion, for tests/debugging:
        #: ``{"move_x": int, "move_y": int, "turn": int}``.
        self.last_sdk_command: Dict[str, int] = {"move_x": 0, "move_y": 0, "turn": 0}

        # The Pi Robot API calls the robot from request handlers and from its
        # watchdog task at the same time; the lock keeps state consistent.
        self._lock = threading.RLock()

    # ------------------------------------------------------------------
    # Identity
    # ------------------------------------------------------------------

    @property
    def robot_mode(self) -> RobotMode:
        return RobotMode.SIMULATOR

    @property
    def connected(self) -> bool:
        return self._connected

    @connected.setter
    def connected(self, value: bool) -> None:
        """Lets tests simulate a lost link."""
        self._connected = bool(value)

    # ------------------------------------------------------------------
    # v1 movement
    # ------------------------------------------------------------------

    def move_analog(self, command: MotionCommand) -> CommandResult:
        """Applies one joystick tick (dead zone -> intensity scale -> clamp)."""
        with self._lock:
            blocked = self._motion_blocked("motion")
            if blocked:
                return blocked

            # An all-zero command is a stop (also covers "inside the dead zone").
            forward = apply_dead_zone(command.forward, self.config.dead_zone)
            strafe = apply_dead_zone(command.strafe, self.config.dead_zone)
            turn = apply_dead_zone(command.turn, self.config.dead_zone)
            if forward == 0.0 and strafe == 0.0 and turn == 0.0:
                self.stop()
                return CommandResult(
                    CommandStatus.ACCEPTED, "motion", "Zero input treated as stop.", self.intensity
                )

            # Total scale: per-intensity scale x global safety cap. Inputs are
            # already in [-1, 1] and both factors are <= 1, so the result can
            # never exceed the SDK range; the min() is defence in depth.
            scale = MOTION_SCALE_FOR_INTENSITY[self.intensity] * self.config.max_motion_scale
            forward_s = max(-1.0, min(1.0, forward * scale))
            strafe_s = max(-1.0, min(1.0, strafe * scale))
            turn_s = max(-1.0, min(1.0, turn * scale))

            self.last_sdk_command = {
                "move_x": round(forward_s * SDK_VX_MAX),
                "move_y": round(strafe_s * SDK_VY_MAX),
                "turn": self._sdk_turn(turn_s),
            }
            self._advance(forward_s * self.step_m, strafe_s * self.step_m, turn_s * self.turn_deg)
            self.speed = math.hypot(forward_s, strafe_s)
            self.moving = True
            self.last_command = "motion"
            return CommandResult(CommandStatus.ACCEPTED, "motion", "Simulated analog motion.", self.intensity)

    def move_discrete(self, direction: Direction, intensity: Optional[Intensity] = None) -> CommandResult:
        """One discrete step. ``intensity`` only picks the step size for this call."""
        with self._lock:
            blocked = self._motion_blocked("motion_discrete")
            if blocked:
                return blocked
            try:
                direction = Direction(direction)
                step_intensity = self.intensity if intensity is None else Intensity(intensity)
            except ValueError as exc:
                return CommandResult(CommandStatus.REJECTED, "motion_discrete", str(exc), self.intensity)

            steps = DISCRETE_STEP_FOR_INTENSITY[step_intensity]
            linear, turn_step = steps["linear"], steps["turn"]
            # Positive = forward / left / turn-left, same as MotionCommand.
            sdk = {"move_x": 0, "move_y": 0, "turn": 0}
            if direction is Direction.FORWARD:
                sdk["move_x"] = linear
            elif direction is Direction.BACKWARD:
                sdk["move_x"] = -linear
            elif direction is Direction.LEFT:
                sdk["move_y"] = linear
            elif direction is Direction.RIGHT:
                sdk["move_y"] = -linear
            elif direction is Direction.TURN_LEFT:
                sdk["turn"] = turn_step
            else:
                sdk["turn"] = -turn_step

            self.last_sdk_command = sdk
            self._advance(
                sdk["move_x"] / SDK_VX_MAX * self.step_m,
                sdk["move_y"] / SDK_VY_MAX * self.step_m,
                sdk["turn"] / SDK_VYAW_MAX * self.turn_deg,
            )
            self.speed = math.hypot(sdk["move_x"] / SDK_VX_MAX, sdk["move_y"] / SDK_VY_MAX)
            self.moving = True
            self.last_command = direction.value
            return CommandResult(
                CommandStatus.ACCEPTED,
                "motion_discrete",
                f"Simulated discrete step: {direction.value} ({step_intensity.value}).",
                self.intensity,  # stored style, NOT the per-call override
            )

    def stop(self) -> CommandResult:
        """Stops locomotion. Always allowed; keeps intensity and gait."""
        with self._lock:
            self.speed = 0.0
            self.moving = False
            self.last_sdk_command = {"move_x": 0, "move_y": 0, "turn": 0}
            # Don't overwrite the e-stop marker: the status should keep showing
            # why the robot is locked until it is reset.
            if not self.emergency_stopped:
                self.last_command = "stop"
            result = _LegacyStopResult(
                CommandStatus.STOP_DISPATCHED, "stop", "Robot stopped.", self.intensity
            )
            result._legacy = self._result(True, "Robot stopped.")
            return result

    # ------------------------------------------------------------------
    # v1 style, posture, actions, reset
    # ------------------------------------------------------------------

    def set_movement_style(self, style: MovementStyle) -> CommandResult:
        """Stores intensity/gait. Never touches posture; rejects unsafe combos."""
        with self._lock:
            if self.emergency_stopped:
                return self._estop_rejection("movement_style")
            reason = check_combination(style.gait, style.intensity, self.posture.height)
            if reason:
                return CommandResult(CommandStatus.REJECTED, "movement_style", reason, self.intensity)
            self.intensity = style.intensity
            self.gait = style.gait
            return CommandResult(
                CommandStatus.ACCEPTED,
                "movement_style",
                f"Style set: intensity={style.intensity.value}, gait={style.gait.value}.",
                self.intensity,
            )

    def set_posture(self, posture: Optional[Posture] = None, **legacy: Any) -> Any:
        """Stores height/attitude. Never touches style; rejects unsafe values."""
        if posture is None:
            # Legacy keyword form used by backend/main.py (see backend/robot/legacy.py).
            from backend.robot.legacy import apply_legacy_posture

            return apply_legacy_posture(self, **legacy)
        with self._lock:
            if self.emergency_stopped:
                return self._estop_rejection("posture")
            reason = check_attitude(posture.roll, posture.pitch, posture.yaw) or check_combination(
                self.gait, self.intensity, posture.height
            )
            if reason:
                return CommandResult(CommandStatus.REJECTED, "posture", reason, self.intensity)
            self.posture = posture
            return CommandResult(CommandStatus.ACCEPTED, "posture", "Posture set.", self.intensity)

    def list_actions(self) -> List[ActionInfo]:
        """Only the approved allowlist (never 255/reset)."""
        return [ActionInfo(id=i, name=n) for i, n in sorted(APPROVED_ACTIONS.items())]

    def perform_action(self, action_id: int) -> CommandResult:
        """Runs an approved action; rejected if unknown, moving or e-stopped."""
        with self._lock:
            if self.emergency_stopped:
                return self._estop_rejection("action")
            if isinstance(action_id, bool) or not isinstance(action_id, int) or action_id not in APPROVED_ACTIONS:
                return CommandResult(
                    CommandStatus.REJECTED, "action", f"Action {action_id!r} is not approved.", self.intensity
                )
            if self.moving:
                return CommandResult(
                    CommandStatus.REJECTED, "action", "Stop the robot before running an action.", self.intensity
                )
            self.last_command = f"action:{action_id}"
            return CommandResult(
                CommandStatus.ACCEPTED,
                "action",
                f"Simulated action {action_id} ({APPROVED_ACTIONS[action_id]}).",
                self.intensity,
            )

    def reset(self) -> CommandResult:
        """Neutral posture, stopped; intensity and gait are kept."""
        with self._lock:
            if self.emergency_stopped:
                return self._estop_rejection("reset")
            self.speed = 0.0
            self.moving = False
            self.last_sdk_command = {"move_x": 0, "move_y": 0, "turn": 0}
            self.posture = Posture()  # neutral: medium height, zero attitude
            self.last_command = "reset"
            return CommandResult(CommandStatus.ACCEPTED, "reset", "Robot reset.", self.intensity)

    @property
    def imu_enabled(self) -> bool:
        return self._imu_enabled

    def set_imu(self, enabled: bool) -> CommandResult:
        """Tracks the IMU self-stabilization flag (nothing to stabilize in simulation)."""
        with self._lock:
            if self.emergency_stopped:
                return self._estop_rejection("imu")
            self._imu_enabled = bool(enabled)
            return CommandResult(CommandStatus.ACCEPTED, "imu", f"IMU stabilization {'on' if enabled else 'off'}.", self.intensity)

    # ------------------------------------------------------------------
    # v1 state
    # ------------------------------------------------------------------

    def read_telemetry(self) -> Telemetry:
        """Simulated *measured* values plus the tracked control state."""
        with self._lock:
            yaw = (self.heading + self.posture.yaw + 180.0) % 360.0 - 180.0
            return Telemetry(
                battery=self.battery_level,
                orientation=Orientation(roll=self.posture.roll, pitch=self.posture.pitch, yaw=round(yaw, 1)),
                firmware=_SIM_FIRMWARE,
                read_errors=[],
                control_state=self.get_control_state(),
            )

    def get_control_state(self) -> ControlState:
        """Snapshot of tracked state (a copy; mutating it changes nothing)."""
        with self._lock:
            return ControlState(
                intensity=self.intensity,
                gait=self.gait,
                posture=replace(self.posture),
                moving=self.moving,
                emergency_stopped=self.emergency_stopped,
                last_command=self.last_command,
            )

    # ------------------------------------------------------------------
    # Emergency stop latch
    # ------------------------------------------------------------------

    def emergency_stop(self) -> Dict[str, Any]:
        """Halts the robot and latches the emergency stop until reset."""
        with self._lock:
            self.speed = 0.0
            self.moving = False
            self.last_command = "emergency_stop"
            self.emergency_stopped = True
            return self._result(True, "EMERGENCY STOP ACTIVATED! Robot immobilized.")

    def reset_emergency_stop(self) -> Dict[str, Any]:
        """Clears the emergency stop latch."""
        with self._lock:
            self.emergency_stopped = False
            self.speed = 0.0
            self.moving = False
            self.last_command = "stop"
            return self._result(True, "Emergency stop cleared. Locomotion restored.")

    # ------------------------------------------------------------------
    # Legacy API (backend/main.py, /api/robot/*)
    # ------------------------------------------------------------------

    def move(self, action: str, speed: float = 0.2) -> Dict[str, Any]:
        """Executes one simulated movement tick.

        Also accepts ``"stop"`` and ``"emergency_stop"`` as actions, because
        ``/api/robot/command`` and the ``/ws`` channel send them through here.
        """
        if not isinstance(action, str):
            return self._result(False, f"Invalid action: {action!r}. Expected a string.")
        action_clean = action.lower().strip()

        # Stop commands are always accepted, even during emergency stop.
        if action_clean == "stop":
            return self.stop()._legacy  # type: ignore[attr-defined,return-value]
        if action_clean == "emergency_stop":
            return self.emergency_stop()

        with self._lock:
            if self.emergency_stopped:
                return self._result(False, "Movement blocked: Emergency stop is active. Reset required.")

            if action_clean not in _MOVE_ACTIONS:
                return self._result(False, f"Unknown movement action: '{action}'.")

            try:
                speed_value = float(speed)
            except (TypeError, ValueError):
                return self._result(False, f"Invalid speed: {speed!r}. Expected a number between 0.0 and 1.0.")
            if math.isnan(speed_value):
                return self._result(False, "Invalid speed: NaN.")
            clamped_speed = max(0.0, min(1.0, speed_value))

            if self.battery_level <= 0.0:
                self.speed = 0.0
                self.moving = False
                return self._result(False, "Movement blocked: Battery depleted.")

            if action_clean in ("forward", "backward"):
                direction = 1.0 if action_clean == "forward" else -1.0
                distance = direction * clamped_speed * self.step_m
                rad = math.radians(self.heading)
                self.x = round(self.x + distance * math.cos(rad), 3)
                self.y = round(self.y + distance * math.sin(rad), 3)
                self._drain_battery(_DRAIN_PER_STEP)
            else:
                direction = 1.0 if action_clean == "left" else -1.0
                self.heading = round((self.heading + direction * self.turn_deg) % 360.0, 1)
                self._drain_battery(_DRAIN_PER_TURN)

            self.speed = clamped_speed
            self.moving = clamped_speed > 0.0
            self.last_command = action_clean
            return self._result(True, f"Simulated movement: {action_clean} at speed {clamped_speed}.")

    def get_status(self) -> Dict[str, Any]:
        """Returns the current state of the simulated robot (legacy shape)."""
        with self._lock:
            return {
                "connected": self.connected,
                "mode": self.mode,
                "battery_level": self.battery_level,
                "position": {
                    "x": self.x,
                    "y": self.y,
                    "heading": self.heading,
                },
                "speed": self.speed,
                "last_command": self.last_command,
                "emergency_stopped": self.emergency_stopped,
                "timestamp": datetime.now(timezone.utc).isoformat(),
                **legacy_status_blocks(self),
            }

    # ------------------------------------------------------------------
    # Helpers
    # ------------------------------------------------------------------

    def _motion_blocked(self, command: str) -> Optional[CommandResult]:
        """Common gate for v1 motion commands; ``None`` means "go ahead"."""
        if self.emergency_stopped:
            return self._estop_rejection(command)
        if not self.connected:
            return CommandResult(CommandStatus.FAILED, command, "Robot not connected.", self.intensity)
        if self.battery_level <= 0.0:
            self.speed = 0.0
            self.moving = False
            return CommandResult(CommandStatus.REJECTED, command, "Battery depleted.", self.intensity)
        # Style and posture are validated when set, so this should never fire;
        # it guards against state being mutated directly.
        reason = check_combination(self.gait, self.intensity, self.posture.height)
        if reason:
            return CommandResult(CommandStatus.REJECTED, command, reason, self.intensity)
        return None

    def _estop_rejection(self, command: str) -> CommandResult:
        return CommandResult(
            CommandStatus.REJECTED,
            command,
            "Blocked: emergency stop is active. Reset required.",
            self.intensity,
        )

    @staticmethod
    def _sdk_turn(turn_scaled: float) -> int:
        """Mimics SDK ``turn()``: clamp to +/-70, raise non-zero |v|<30 to 30."""
        value = round(turn_scaled * SDK_VYAW_MAX)
        if value == 0:
            return 0
        magnitude = min(max(abs(value), SDK_VYAW_MIN_NONZERO), SDK_VYAW_MAX)
        return int(math.copysign(magnitude, value))

    def _advance(self, forward_m: float, strafe_m: float, turn_deg: float) -> None:
        """Integrates one tick: turn first, then move in the new heading frame."""
        self.heading = round((self.heading + turn_deg) % 360.0, 1)
        rad = math.radians(self.heading)
        # Left of heading is heading + 90 degrees.
        self.x = round(self.x + forward_m * math.cos(rad) - strafe_m * math.sin(rad), 3)
        self.y = round(self.y + forward_m * math.sin(rad) + strafe_m * math.cos(rad), 3)
        self._drain_battery(_DRAIN_PER_TURN if forward_m == 0.0 and strafe_m == 0.0 else _DRAIN_PER_STEP)

    def _drain_battery(self, amount: float) -> None:
        """Simulates battery depletion during operations."""
        self.battery_level = max(0.0, round(self.battery_level - amount, 2))

    def _result(self, success: bool, message: str) -> Dict[str, Any]:
        """Builds the standard legacy command response."""
        return {
            "success": success,
            "message": message,
            "telemetry": self.get_status(),
        }
